/// Framebuffer state
static mut FB_STATE: FbState = FbState::new();

struct FbState {
    addr: *mut u32,
    width: u32,
    height: u32,
    pitch: u32,
    cursor_x: u32,
    cursor_y: u32,
    initialized: bool,
}

impl FbState {
    const fn new() -> Self {
        Self {
            addr: core::ptr::null_mut(),
            width: 0,
            height: 0,
            pitch: 0,
            cursor_x: 0,
            cursor_y: 0,
            initialized: false,
        }
    }
}

/// Initialize framebuffer debug output
pub fn init(fb_info: &FramebufferInfo) {
    unsafe {
        if fb_info.addr.as_u64() == 0 || fb_info.width == 0 || fb_info.height == 0 {
            return; // No framebuffer available
        }
        
        FB_STATE.addr = fb_info.addr.as_u64() as *mut u32;
        FB_STATE.width = fb_info.width;
        FB_STATE.height = fb_info.height;
        FB_STATE.pitch = fb_info.pitch;
        FB_STATE.cursor_x = 0;
        FB_STATE.cursor_y = 0;
        FB_STATE.initialized = true;
        
        // Clear screen to black
        clear_screen();
        
        // Print welcome message
        puts("WebbOS Bootloader\n");
        puts("=================\n\n");
    }
}

/// Clear the screen to black
pub fn clear_screen() {
    unsafe {
        if !FB_STATE.initialized {
            return;
        }
        
        let fb = FB_STATE.addr;
        let height = FB_STATE.height;
        let pitch_pixels = FB_STATE.pitch / 4;
        
        for y in 0..height {
            for x in 0..pitch_pixels {
                write_volatile(fb.add((y * pitch_pixels + x) as usize), 0x00000000);
            }
        }
        
        FB_STATE.cursor_x = 0;
        FB_STATE.cursor_y = 0;
    }
}

/// Print a string to the framebuffer
pub fn puts(s: &str) {
    for c in s.bytes() {
        putc(c);
    }
}

/// Print a single character
pub fn putc(c: u8) {
    unsafe {
        if !FB_STATE.initialized {
            return;
        }
        
        match c {
            b'\n' => {
                FB_STATE.cursor_x = 0;
                FB_STATE.cursor_y += 10; // 8px font + 2px spacing
                scroll_if_needed();
            }
            b'\r' => {
                FB_STATE.cursor_x = 0;
            }
            _ => {
                // Draw character
                draw_char(c, FB_STATE.cursor_x, FB_STATE.cursor_y);
                
                // Advance cursor
                FB_STATE.cursor_x += 8;
                if FB_STATE.cursor_x + 8 > FB_STATE.width {
                    FB_STATE.cursor_x = 0;
                    FB_STATE.cursor_y += 10;
                    scroll_if_needed();
                }
            }
        }
    }
}

/// Draw a single character at position
fn draw_char(c: u8, x: u32, y: u32) {
    unsafe {
        let font = FONT_8X8[c as usize];
        let fb = FB_STATE.addr;
        let pitch_pixels = FB_STATE.pitch / 4;
        
        for row in 0..8 {
            let font_row = font[row];
            for col in 0..8 {
                if font_row & (1 << (7 - col)) != 0 {
                    let px = x + col;
                    let py = y + row as u32;
                    
                    if px < FB_STATE.width && py < FB_STATE.height {
                        let offset = (py * pitch_pixels + px) as usize;
                        write_volatile(fb.add(offset), 0xFFFFFFFF); // White text
                    }
                }
            }
        }
    }
}

/// Scroll screen if cursor is at bottom
fn scroll_if_needed() {
    unsafe {
        if FB_STATE.cursor_y + 10 > FB_STATE.height {
            // Simple scroll: just wrap around for now
            FB_STATE.cursor_y = 0;
            clear_screen();
        }
    }
}

/// Print a hexadecimal number
pub fn puthex(n: u64) {
    puts("0x");
    if n == 0 {
        putc(b'0');
        return;
    }
    
    let mut started = false;
    for i in (0..64).step_by(4).rev() {
        let nibble = ((n >> i) & 0xF) as u8;
        if nibble != 0 || started || i == 0 {
            started = true;
            let c = if nibble < 10 {
                b'0' + nibble
            } else {
                b'A' + nibble - 10
            };
            putc(c);
        }
    }
}

/// Print a decimal number
pub fn putdec(n: u64) {
    if n == 0 {
        putc(b'0');
        return;
    }
    
    // Find highest power of 10
    let mut divisor = 1u64;
    while n / divisor >= 10 {
        divisor *= 10;
    }
    
    // Print digits
    let mut remaining = n;
    while divisor > 0 {
        let digit = (remaining / divisor) as u8;
        putc(b'0' + digit);
        remaining %= divisor;
        divisor /= 10;
    }
}

/// Check if framebuffer is initialized
pub fn is_initialized() -> bool {
    unsafe { FB_STATE.initialized }
}
